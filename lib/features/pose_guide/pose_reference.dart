import 'dart:ui';

/// Normalized pose landmarks are hand-authored reference illustrations, not
/// detected body points. All focal lengths are full-frame equivalents.
class PoseReference {
  const PoseReference({
    required this.id,
    required this.title,
    required this.scene,
    required this.framing,
    required this.style,
    required this.description,
    required this.cameraPosition,
    required this.focalLength,
    required this.mistakes,
    required this.instructions,
    required this.joints,
    this.photoAsset,
    this.photographer,
    this.photoSource,
    this.peopleCount = 1,
  });
  final String id,
      title,
      scene,
      framing,
      style,
      description,
      cameraPosition,
      focalLength;
  final List<String> mistakes, instructions;
  final String? photoAsset, photographer, photoSource;
  final int peopleCount;
  bool get supportsOverlay => joints.length == 14;

  /// head, neck, left/right shoulders, left elbow/wrist, right elbow/wrist,
  /// left/right hips, left knee/ankle, right knee/ankle.
  final List<Offset> joints;
}

